class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that adds running headers, running footers, and page numbers.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()

        # Header bar
        self.setFillColor(PRIMARY_INDIGO)
        self.rect(0, 11 * inch - 6, 8.5 * inch, 6, fill=1, stroke=0)

        # Footer
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(COLOR_RED)
        disclaimer = "PROTOTYPE SCREENING REPORT — This is not a medical diagnosis. Generated by NeuroVoice research platform. Consult a neurologist."
        self.drawCentredString(4.25 * inch, 0.45 * inch, disclaimer)

        self.setFont("Helvetica", 7)
        self.setFillColor(TEXT_MUTED)
        institution = "Developed in collaboration with Jabalpur Medical College, MP, India"
        self.drawString(0.75 * inch, 0.28 * inch, institution)

        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(7.75 * inch, 0.28 * inch, page_str)

        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(0.75 * inch, 0.6 * inch, 7.75 * inch, 0.6 * inch)

        self.restoreState()


